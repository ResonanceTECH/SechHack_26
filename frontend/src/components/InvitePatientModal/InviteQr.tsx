/** Static QR-looking matrix for invite mock (visual fidelity, not a real encoder). */
const MODULES = [
  '1111111010101110101111111',
  '1000001011101010101000001',
  '1011101010001110101011101',
  '1011101001010101101011101',
  '1011101010111010101011101',
  '1000001010101010101000001',
  '1111111010101010101111111',
  '0000000011010110100000000',
  '1101111100101011111101110',
  '0101010011010101010010101',
  '1010101110101010101110101',
  '0101010001010101010001010',
  '1110101110101110101110101',
  '0000000010101010101010101',
  '1111111011010110101011101',
  '1000001010101010110100001',
  '1011101011110101010111101',
  '1011101000101010101001010',
  '1011101010101110101110101',
  '1000001011010101010010110',
  '1111111010101010101010101',
  '0000000001010110101110101',
  '1101011110101010110101010',
  '0100100011010101010010101',
  '1010111010101110101110111',
]

interface InviteQrProps {
  size?: number
  label?: string
}

export function InviteQr({ size = 168, label = 'QR-код приглашения' }: InviteQrProps) {
  const n = MODULES.length
  const cell = size / n

  return (
    <svg
      width={size}
      height={size}
      viewBox={`0 0 ${size} ${size}`}
      role="img"
      aria-label={label}
    >
      <rect width={size} height={size} fill="#fff" />
      {MODULES.flatMap((row, y) =>
        [...row].flatMap((bit, x) =>
          bit === '1'
            ? [
                <rect
                  key={`${x}-${y}`}
                  x={x * cell}
                  y={y * cell}
                  width={cell}
                  height={cell}
                  fill="#1B2440"
                />,
              ]
            : [],
        ),
      )}
    </svg>
  )
}
